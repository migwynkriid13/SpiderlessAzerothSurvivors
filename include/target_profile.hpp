// Current Win64 read ABI: RCX=output, RDX=chain, R8=path, R9=path length;
// RAX returns output. Error is capacity==UINT64_MAX; other words remain opaque.
struct NativeReadResult {
    std::uint64_t capacity;
    std::uint8_t* data;
    std::uint64_t size;
};
static_assert(sizeof(NativeReadResult) == 24);
static_assert(offsetof(NativeReadResult, data) == 8);
static_assert(offsetof(NativeReadResult, size) == 16);

